#!/usr/bin/env python3
"""Generate the compact status descriptor from the vendor's protobufjs bundle."""
import argparse
import json
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("bundle", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
flat = {}

def walk(node, prefix=""):
    for name, value in node.get("nested", {}).items():
        path = f"{prefix}.{name}" if prefix else name
        if "fields" in value or "values" in value:
            flat[path] = {key: value[key] for key in ("fields", "values") if key in value}
        walk(value, path)

walk(json.loads(args.bundle.read_text()))
args.output.write_text('''// Derived from busy-app/busylib-ts src/StateStream/types/bundle.json (MIT).
// See THIRD_PARTY_NOTICES.md. Generated by scripts/generate-status-schema.py.
import Foundation

enum StatusSchema {
    static let types = try! JSONDecoder().decode([String: StatusProto.TypeInfo].self, from: Data(schema.utf8))
    private static let schema = #"""
''' + json.dumps(flat, separators=(",", ":")) + '\n"""#\n}\n')
